def blob(R, cx, cy, rx, ry, rot, k=7, jit=0.22):
    pts = []
    for i in range(k):
        a = 2 * math.pi * i / k + R.uniform(-0.2, 0.2)
        r = 1 + R.uniform(-jit, jit)
        x, y = math.cos(a) * rx * r, math.sin(a) * ry * r
        c, s = math.cos(math.radians(rot)), math.sin(math.radians(rot))
        pts.append((cx + x * c - y * s, cy + x * s + y * c))
    return pts


def ring(R, cx, cy, rx, ry, rot, t=0.6):
    pts = blob(R, cx, cy, rx, ry, rot)
    outer = cr(pts)
    inner = cr([(cx + (x - cx) * t + R.uniform(-1.5, 1.5), cy + (y - cy) * t + R.uniform(-1.5, 1.5)) for x, y in pts])
    return [outer, hole(inner)]


