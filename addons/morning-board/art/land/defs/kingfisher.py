from geom import Animal, cr, ell, circ, poly, ribbon


def build():
    A = Animal("collared-kingfisher", "Collared kingfisher", "Todiramphus chloris", 500, 420)
    sil = cr([(156, 120), (180, 96), (222, 90), (256, 108), (276, 140), (300, 180), (330, 230),
              (364, 290), (398, 352), (404, 372), (386, 376), (350, 320), (316, 292), (290, 286),
              (250, 268), (214, 236), (192, 200), (170, 172), (156, 160)])
    A.add(sil, "dots", False)
    whites = [cr([(160, 150), (186, 150), (220, 176), (262, 200), (300, 230), (318, 264), (330, 300),
                  (300, 310), (240, 290), (180, 240), (140, 180)]),
              ribbon([(186, 150), (230, 160), (266, 150), (282, 140)], [(0, 6), (0.6, 7), (1, 4)], n=6)]
    A.add(whites, "paper", False)
    mask = ribbon([(158, 132), (196, 128), (236, 128), (268, 136)], [(0, 6), (0.4, 9), (1, 3)], n=6)
    feathers = [ribbon([(270, 170 + k * 18), (300, 196 + k * 20), (330, 236 + k * 18)],
                       [(0, 0), (0.5, 1.8), (1, 0)], n=6) for k in range(3)]
    A.add([mask] + feathers, "ink", False)
    A.add(sil, "none", True, 2.5)
    branch = ribbon([(110, 318), (300, 306), (480, 300)], [(0, 10), (1, 9)], n=8)
    A.add(branch, "dots", True, 2.5)
    feet = [cr([(262, 284), (280, 288), (282, 304), (258, 304)]),
            ribbon([(254, 300), (248, 308), (250, 316)], [(0, 3.5), (1, 1.5)], n=4),
            ribbon([(266, 300), (264, 310), (268, 318)], [(0, 3.5), (1, 1.5)], n=4),
            ribbon([(278, 300), (280, 310), (286, 316)], [(0, 3.5), (1, 1.5)], n=4)]
    upper = cr([(162, 118, 'c'), (110, 128), (60, 140), (24, 150, 'c'), (70, 147), (120, 142), (166, 140, 'c')])
    A.add(feet + [upper], "ink", True, 2)
    lower = cr([(166, 140, 'c'), (120, 142), (70, 147), (24, 150, 'c'), (66, 156), (116, 160), (164, 162, 'c')])
    A.add(lower, "paper", True, 2)
    A.add(circ(198, 128, 7.5), "paper", False)
    A.add(circ(197, 128, 4.5), "ink", False)
    return A
