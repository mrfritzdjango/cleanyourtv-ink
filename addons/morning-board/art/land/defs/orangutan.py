from geom import Animal, cr, ell, circ, poly, ribbon, tufts, sym, mirror_x


def dedupe(pts):
    out = []
    for p in pts:
        if not out or abs(p[0] - out[-1][0]) + abs(p[1] - out[-1][1]) > 0.5:
            out.append(p)
    if abs(out[0][0] - out[-1][0]) + abs(out[0][1] - out[-1][1]) <= 0.5:
        out.pop()
    return out


def hairy(pts, step=20, amp=16, down=(0, 12), seed=1):
    return tufts(pts, step, amp, down, 0.45, seed, side=-1)


