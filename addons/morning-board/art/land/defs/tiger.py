import random
from geom import Animal, cr, ell, circ, poly, ribbon


def build():
    A = Animal("malayan-tiger", "Malayan tiger", "Panthera tigris jacksoni", 600, 400)
    sil = cr([
        (30, 160), (36, 138), (54, 112), (80, 94), (90, 82), (100, 68), (116, 64), (128, 76),
        (132, 92), (152, 100), (182, 110), (232, 98), (300, 112), (380, 110), (460, 102),
        (506, 114), (526, 128), (552, 148), (568, 186), (574, 232), (571, 280), (576, 318),
        (586, 340), (588, 356), (574, 364), (560, 352), (550, 322), (546, 280), (548, 232),
        (542, 196), (528, 168, 'c'), (532, 210), (526, 250), (516, 278), (512, 320),
        (514, 352), (522, 368), (512, 378, 'c'), (468, 378, 'c'), (464, 364), (476, 346),
        (482, 314), (482, 288), (474, 254), (456, 236, 'c'), (448, 280), (446, 330),
        (452, 366, 'c'), (414, 368, 'c'), (416, 336), (420, 296), (414, 256), (376, 254),
        (326, 264), (288, 270), (278, 280), (270, 314), (272, 362, 'c'), (236, 364, 'c'),
        (240, 322), (234, 292, 'c'), (228, 326), (226, 352), (234, 366), (228, 378, 'c'),
        (174, 378, 'c'), (172, 364), (182, 348), (186, 300), (178, 262), (164, 236),
        (150, 226), (134, 228), (116, 222), (88, 214), (66, 208), (54, 200), (42, 190), (32, 176),
    ])
    A.add(sil, "dots", False)
    whites = [
        cr([(30, 172), (52, 166), (78, 168), (100, 176), (124, 182), (146, 196), (156, 230),
            (120, 240), (60, 236), (24, 200)]),
        cr([(286, 270), (310, 248), (360, 244), (410, 250), (440, 270), (420, 290), (300, 290)]),
        ell(82, 120, 12, 6.5, -14),
    ]
    A.add(whites, "paper", False)
    R = random.Random(11)
    st = []
    x = 194
    while x < 500:
        top = 90
        f = (x - 194) / 306.0
        lean = 10 - 26 * f          # bottom leans forward at the shoulder, back at the hip
        L = R.uniform(0.55, 0.9) * (262 - top)
        w = R.uniform(6, 9.5)
        wob = R.uniform(-7, 7)
        pts = [(x, top), (x + lean * 0.3 + wob, top + L * 0.35), (x + lean * 0.65 - wob * 0.6, top + L * 0.7),
               (x + lean, top + L)]
        st.append(ribbon(pts, [(0, w * 0.8), (0.3, w), (0.75, w * 0.55), (1, 0)], n=10))
        if R.random() < 0.5:
            y0 = top + L * R.uniform(0.75, 0.95) + 10
            bx = x + lean + R.uniform(4, 10)
            st.append(ribbon([(bx, y0), (bx + lean * 0.2 + 3, y0 + 20), (bx + lean * 0.3, y0 + 40)],
                             [(0, 0), (0.4, w * 0.6), (1, 0)], n=6))
        x += R.uniform(23, 31)
    for k in range(4):
        st.append(ribbon([(540, 146 + k * 26), (510, 166 + k * 26), (486, 190 + k * 26)],
                         [(0, 6.5), (1, 0)], n=6))
    for k in range(3):
        st.append(ribbon([(146, 140 + k * 30), (172, 152 + k * 28), (196, 170 + k * 26)],
                         [(0, 0), (0.4, 5.5), (1, 0)], n=6))
    for y in (276, 304, 330):
        st.append(ribbon([(174, y), (196, y + 5), (214, y + 3)], [(0, 6), (1, 0)], n=5))
        st.append(ribbon([(476, y + 4), (496, y + 9), (512, y + 7)], [(0, 6), (1, 0)], n=5))
    for (x0, y0) in [(546, 168), (562, 205), (565, 245), (563, 285), (566, 318)]:
        st.append(ribbon([(x0 - 22, y0 - 12), (x0, y0), (x0 + 22, y0 + 6)],
                         [(0, 3), (0.5, 7), (1, 3)], n=6))
    st.append(ell(578, 352, 18, 16))
    for (x0, y0, x1, y1) in [(96, 86, 94, 108), (110, 90, 106, 112), (124, 96, 118, 116),
                             (138, 104, 130, 124)]:
        st.append(ribbon([(x0, y0), ((x0 + x1) / 2 + 2, (y0 + y1) / 2), (x1, y1)], [(0, 4.5), (1, 0)], n=5))
    for k in range(3):
        st.append(ribbon([(156, 170 + k * 16), (132, 176 + k * 16), (110, 186 + k * 14)],
                         [(0, 6.5), (1, 0)], n=5))
    st.append(cr([(30, 156), (44, 152), (46, 164), (36, 172), (28, 168)]))  # nose
    A.add(st, "ink", False)
    A.mask(sil)
    A.add(sil, "none", True, 2.6)
    A.add(cr([(64, 134), (76, 126), (92, 128), (82, 139)]), "ink", False)
    A.add(circ(79, 131, 2.3), "paper", False)
    det = [
        cr([(40, 186), (54, 194), (70, 198)], closed=False),
        cr([(54, 180), (30, 178), (8, 182)], closed=False),
        cr([(56, 186), (32, 190), (10, 200)], closed=False),
        cr([(58, 191), (38, 202), (20, 216)], closed=False),
        cr([(102, 76), (112, 82), (116, 94)], closed=False),
        cr([(446, 282), (450, 250), (462, 236)], closed=False),
    ]
    A.add(det, "none", True, 1.6)
    return A
